package shootemup

func placementFor(pattern, count, idx int) vec2 {
	if pattern < 0 || pattern >= len(placementPatterns) {
		return vec2{}
	}
	rows := placementPatterns[pattern]
	row := rows[clampInt(count-1, 0, len(rows)-1)]
	return row[clampInt(idx, 0, len(row)-1)]
}

func clampInt(v, lo, hi int) int {
	if v < lo {
		return lo
	}
	if v > hi {
		return hi
	}
	return v
}

func pts(v ...float64) []vec2 {
	out := make([]vec2, 0, len(v)/2)
	for i := 0; i+1 < len(v); i += 2 {
		out = append(out, vec2{v[i], v[i+1]})
	}
	return out
}

